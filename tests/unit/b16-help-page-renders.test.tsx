// ── The page under contract ─────────────────────────────────────

type HelpPageComponent = (props: {
  params: Promise<{ slug?: string[] }>;
}) => Promise<ReactElement>;

function helpPage(): HelpPageComponent {
  let mod: { default?: unknown };
  try {
    mod = require("../../src/app/help/[[...slug]]/page") as { default?: unknown };
  } catch (err) {
    throw new Error(
      "B16 owes src/app/help/[[...slug]]/page.tsx (contract 3.1). require() said: " + String(err),
    );
  }
  if (typeof mod.default !== "function") {
    throw new Error("src/app/help/[[...slug]]/page.tsx must default-export the page (contract 3.1).");
  }
  return mod.default as HelpPageComponent;
}

/** The loader's cache is per process, so each test clears it after moving
 *  PS_HELP_DIR. Silent while the module is missing: the page's own require
 *  says which file B16 owes, and one sentence per test is enough. */
function resetHelpCache(): void {
  try {
    const mod = require("@/lib/help/help-source") as { resetHelpCache?: () => void };
    mod.resetHelpCache?.();
  } catch {
    /* B16 owes src/lib/help/help-source.ts (contract 2.2). */
  }
}

async function renderHelp(slug?: string[]): Promise<HTMLElement> {
  const Page = helpPage();
  const ui = await Page({ params: Promise.resolve(slug ? { slug } : {}) });
  return render(ui).container;
}

