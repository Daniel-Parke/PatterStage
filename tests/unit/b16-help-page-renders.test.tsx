let sandbox = "";
let builtDir = "";
let emptyDir = "";
const savedEnv = { ...process.env };

function write(path: string, body: string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, body, "utf-8");
}

beforeAll(() => {
  sandbox = mkdtempSync(join(tmpdir(), "ps-b16-help-"));
  builtDir = join(sandbox, "built");
  emptyDir = join(sandbox, "not-built");
  mkdirSync(emptyDir, { recursive: true });

  write(join(builtDir, "manifest.json"), JSON.stringify(MANIFEST));
  write(join(builtDir, "concepts.json"), JSON.stringify(CONCEPTS));
  write(join(builtDir, "search.json"), JSON.stringify(SEARCH));
  write(join(builtDir, "fragments", "start-here", "what-it-is.html"), INDEX_FRAGMENT);
  write(join(builtDir, "fragments", "start-here", "tour", "missions.html"), "<p>The tour stop.</p>");
  write(join(builtDir, "fragments", "guides", "dashboard.html"), "<p>The board.</p>");
  write(join(builtDir, "fragments", "guides", "work-missions.html"), MISSIONS_FRAGMENT);
  // reference/api is in the manifest with NO fragment on purpose: contract 3.3.

  // Plantable proof that a traversal is refused rather than served.
  write(join(sandbox, "secret.html"), "<p>NOT-FOR-THE-BROWSER</p>");
});

afterAll(() => {
  process.env = { ...savedEnv };
  if (sandbox) rmSync(sandbox, { recursive: true, force: true });
});

beforeEach(() => {
  mockNav.pathname = "/help";
  mockRecordEvent.mockClear();
  process.env.PS_HELP_DIR = builtDir;
  resetHelpCache();
});

afterEach(() => {
  delete process.env.PS_HELP_DIR;
  resetHelpCache();
});

function useUnbuiltCorpus(): void {
  process.env.PS_HELP_DIR = emptyDir;
  resetHelpCache();
}

