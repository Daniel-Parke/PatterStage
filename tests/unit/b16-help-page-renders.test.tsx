// ═══════════════════════════════════════════════════════════════
// B16 oracle, the Help screen: src/app/help/[[...slug]]/page.tsx.
//
// Contract section 3. The Help page is a SERVER component (the first one in
// the app; every other page.tsx is "use client"), so it is awaited and its
// returned tree is rendered. It renders the fragment inside AppPageShell and
// PageHeader with HelpNav, HelpSearch and prev/next, and NO iframe: decision 3
// said iframe, B16's bullet overrules it, and an oracle that did not say so
// would let the cheaper answer back in.
//
// The corpus is a REAL one, written to a temp directory and pointed at with
// PS_HELP_DIR (contract 2.2), not a module double. public/help/ is git-ignored
// and generated by B15's prebuild, so a test that read the checkout's copy
// would be green on the operator's machine and red on a fresh clone; and a
// test that doubled the loader would prove the page renders whatever it is
// handed while proving nothing about the file it is meant to read. The env
// override exists precisely so the isolated instance and this oracle can hand
// it a corpus.
//
// Only recordEvent is doubled, because the alternative is a database.
// ═══════════════════════════════════════════════════════════════

