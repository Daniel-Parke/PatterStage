// ── /help itself, and the two ways a slug can be wrong (3.1) ────

describe("the address resolves before anything is read", () => {
  it("renders the first page of the reading order at /help, with no slug", async () => {
    await renderHelp();
    expect(screen.getByRole("heading", { level: 1 })).toHaveTextContent("What PatterStage is");
    expect(screen.getByTestId("help-fragment")).toHaveTextContent("A fixture body for the first page.");
  });

  it("404s a slug the manifest does not carry", async () => {
    mockNav.pathname = "/help/guides/nope";
    await expect(renderHelp(["guides", "nope"])).rejects.toThrow("NEXT_NOT_FOUND");
  });

  it("404s a traversal rather than serving what is above the corpus", async () => {
    mockNav.pathname = "/help/..";
    await expect(renderHelp(["..", "..", "secret"])).rejects.toThrow("NEXT_NOT_FOUND");
    expect(screen.queryByText(/NOT-FOR-THE-BROWSER/)).toBeNull();
  });
});

// ── The analytics emit (contract 3.5) ───────────────────────────

describe("help.opened is recorded from the server, once, for the page that rendered", () => {
  it("records the slug that was opened", async () => {
    mockNav.pathname = "/help/guides/work-missions";
    await renderHelp(["guides", "work-missions"]);
    expect(mockRecordEvent).toHaveBeenCalledTimes(1);
    expect(mockRecordEvent).toHaveBeenCalledWith("help.opened", {
      entityType: "help",
      entityId: "guides/work-missions",
    });
  });

  it("records the resolved index slug when /help is opened with no slug", async () => {
    await renderHelp();
    expect(mockRecordEvent).toHaveBeenCalledWith("help.opened", {
      entityType: "help",
      entityId: "start-here/what-it-is",
    });
  });

  it("records nothing for a page that 404s", async () => {
    mockNav.pathname = "/help/guides/nope";
    await expect(renderHelp(["guides", "nope"])).rejects.toThrow("NEXT_NOT_FOUND");
    expect(mockRecordEvent).not.toHaveBeenCalled();
  });
});

// ── The two empties (contract 3.6, 3.3) ─────────────────────────

describe("a corpus that has not been built says so, and does not 404 or crash", () => {
  it("names the command that builds it, and records nothing", async () => {
    useUnbuiltCorpus();
    await renderHelp();
    expect(screen.getByText(/has not been built/i)).toBeInTheDocument();
    expect(screen.getByText(/npm run docs:build/)).toBeInTheDocument();
    expect(mockRecordEvent).not.toHaveBeenCalled();
  });

  it("still renders the app frame, so the rail's Help entry leads somewhere", async () => {
    useUnbuiltCorpus();
    await renderHelp();
    expect(screen.getByRole("heading", { level: 1 })).toBeInTheDocument();
  });

  it("does not 404 a slug it cannot check", async () => {
    useUnbuiltCorpus();
    mockNav.pathname = "/help/guides/work-missions";
    await expect(renderHelp(["guides", "work-missions"])).resolves.toBeDefined();
  });
});

describe("a manifest entry whose fragment is missing is an alert, not an empty page", () => {
  it("says so rather than rendering a blank article", async () => {
    mockNav.pathname = "/help/reference/api";
    await renderHelp(["reference", "api"]);
    expect(screen.getByRole("alert")).toHaveTextContent(/docs:build/);
    expect(screen.queryByTestId("help-fragment")).toBeNull();
  });
});
