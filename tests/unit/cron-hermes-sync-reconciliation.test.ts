interface DbJobOverrides {
  schedule?: string;
  schedule_display?: string | null;
  enabled?: boolean;
}

function makeDbJob(
  id: string,
  name: string,
  overrides: DbJobOverrides = {},
) {
  return {
    id,
    name,
    prompt: "<hermes_mission/>",
    enabled: overrides.enabled ?? true,
    schedule: overrides.schedule ?? "*/30 * * * *",
    schedule_display: overrides.schedule_display ?? "every 30m",
    state: "scheduled",
    hermes_job_id: id,
    repeat: { times: null as number | null, completed: 0 },
    deliver: "none",
    script: "",
    profile_name: "default",
    created_at: "2026-06-10T00:00:00.000Z",
    last_run_at: null,
    next_run_at: null,
    last_status: null,
    skills: [],
    model: "MiniMax-M3",
    provider: "minimax",
    base_url: null,
    workdir: "",
  };
}
